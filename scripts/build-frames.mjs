#!/usr/bin/env node

// Decodes sprites/<mon>/*.gif with ffmpeg and writes hooks/frames.js, with the sheets
// themselves in hooks/frames/<n>.js, each under the 1 MiB a hooks module may be.
// Each frame becomes rows of palette letters plus its duration, cropped per mon
// to the box every one of its frames fits in.
// Add a mon by dropping its four GIFs from jakobhoeg/vscode-pokemon into sprites/<mon>/.
// A mon with only its default GIFs, like most of gen 5, shows its default colors as shiny.
// Run from anywhere: node scripts/build-frames.mjs

import { execFileSync } from 'node:child_process'
import { existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..')
const VARIANTS = ['default', 'shiny']
const ANIMS = ['idle', 'walk']
const LETTERS = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ'
const PART_BYTES = 900 * 1024
const HEADER = `// Generated by scripts/build-frames.mjs from sprites/<mon>/*.gif. Do not edit by hand.
`

function decode(file) {
  const [w, h] = execFileSync('ffprobe', [
    '-v', 'error', '-select_streams', 'v:0', '-show_entries', 'stream=width,height', '-of', 'csv=p=0', file,
  ]).toString().trim().split(',').map(Number)
  const raw = execFileSync('ffmpeg', [
    '-v', 'error', '-i', file, '-fps_mode', 'passthrough',
    '-f', 'rawvideo', '-pix_fmt', 'rgba', '-',
  ])
  const durations = execFileSync('ffprobe', [
    '-v', 'error', '-show_entries', 'frame=duration_time', '-of', 'csv=p=0', file,
  ]).toString().trim().split('\n').map((s) => Math.round(Number(s) * 1000) || 100)

  const frameBytes = w * h * 4
  const frames = []
  for (let off = 0, k = 0; off < raw.length; off += frameBytes, k++) {
    const px = []
    for (let i = 0; i < w * h; i++) {
      const p = off + i * 4
      px.push(raw[p + 3] > 127 ? (raw[p] << 16) | (raw[p + 1] << 8) | raw[p + 2] : null)
    }
    frames.push({ ms: durations[k] ?? 100, px })
  }
  return { size: w, frames }
}

const gifOf = (mon, v, a) => join(ROOT, 'sprites', mon, `${v}_${a}_8fps.gif`)
const hasVariant = (mon, v) => ANIMS.every((a) => existsSync(gifOf(mon, v, a)))

function buildMon(mon) {
  const variants = VARIANTS.filter((v) => hasVariant(mon, v))
  const sheets = {}
  let size = 0
  for (const v of variants) {
    sheets[v] = {}
    for (const a of ANIMS) {
      const decoded = decode(gifOf(mon, v, a))
      size = decoded.size
      sheets[v][a] = decoded.frames
    }
  }

  let minX = size, minY = size, maxX = -1, maxY = -1
  for (const v of variants) for (const a of ANIMS) for (const { px } of sheets[v][a]) {
    px.forEach((c, i) => {
      if (c === null) return
      const x = i % size, y = Math.floor(i / size)
      minX = Math.min(minX, x); maxX = Math.max(maxX, x)
      minY = Math.min(minY, y); maxY = Math.max(maxY, y)
    })
  }

  const out = { width: maxX - minX + 1, height: maxY - minY + 1, variants: {} }
  for (const v of variants) {
    const palette = []
    const letter = (c) => {
      if (c === null) return '.'
      let i = palette.indexOf(c)
      if (i < 0) i = palette.push(c) - 1
      if (i >= LETTERS.length) throw new Error(`${mon} ${v}: more than ${LETTERS.length} colors`)
      return LETTERS[i]
    }
    const anims = {}
    for (const a of ANIMS) {
      anims[a] = sheets[v][a].map(({ ms, px }) => {
        const rows = []
        for (let y = minY; y <= maxY; y++) {
          let row = ''
          for (let x = minX; x <= maxX; x++) row += letter(px[y * size + x])
          rows.push(row)
        }
        return { ms, rows }
      })
    }
    out.variants[v] = { palette: palette.map((c) => '#' + c.toString(16).padStart(6, '0')), ...anims }
  }
  return out
}

const mons = readdirSync(join(ROOT, 'sprites'), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name)
  .sort()

const sprites = Object.fromEntries(mons.map((mon) => [mon, buildMon(mon)]))

// One line per mon keeps the files small and diffs readable
const lines = Object.entries(sprites).map(([mon, s]) => `  ${JSON.stringify(mon)}: ${JSON.stringify(s)},`)
const parts = [[]]
let size = 0
for (const line of lines) {
  if (size + line.length > PART_BYTES && parts.at(-1).length > 0) {
    parts.push([])
    size = 0
  }
  parts.at(-1).push(line)
  size += line.length + 1
}
const partsDir = join(ROOT, 'hooks', 'frames')
rmSync(partsDir, { recursive: true, force: true })
mkdirSync(partsDir)
parts.forEach((part, i) => writeFileSync(join(partsDir, `${i + 1}.js`), `${HEADER}\nexport const PART = {\n${part.join('\n')}\n}\n`))

const shinyless = mons.filter((mon) => !sprites[mon].variants.shiny)
const imports = parts.map((_, i) => `import { PART as PART_${i + 1} } from './frames/${i + 1}.js'`)
const body = `${HEADER}// Each frame is its duration and rows of palette letters; '.' is transparent.

${imports.join('\n')}

export const SPRITES = { ${parts.map((_, i) => `...PART_${i + 1}`).join(', ')} }

// Mons with no shiny GIFs show their default sheet as shiny
export const SHINYLESS = new Set(${JSON.stringify(shinyless)})
for (const mon of SHINYLESS) SPRITES[mon].variants.shiny = SPRITES[mon].variants.default
`
writeFileSync(join(ROOT, 'hooks', 'frames.js'), body)
for (const [mon, s] of Object.entries(sprites)) {
  const counts = ANIMS.map((a) => `${a} ${s.variants.default[a].length}f`).join(', ')
  console.log(`${mon}: ${s.width}x${s.height}px, ${counts}`)
}
